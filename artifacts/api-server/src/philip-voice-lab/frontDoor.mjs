/**
 * Compose a response for the non-deep intents entirely in-process (deterministic).
 * Returns null for intents that should be handled by the deep brain.
 */
export function composeFrontDoorResponse({ intent, state, transcript, personalMeaning, reciprocal }) {
  const seed = state.turnCount;
  switch (intent) {
    case INTENT.GREETING: {
      if (isHybridGreetingReciprocal(transcript)) {
        const status = extractOpeningStatusBrief(transcript);
        const name = maybeName(state, { force: !state.greeted });
        let text = pick(HYBRID_GREETING_TEMPLATES, seed)(status, name);
        // Never re-ask how they are when they already said.
        if (status) text = text.replace(/\bhow are you( doing| today)?\??/gi, "").replace(/\s+/g, " ").trim();
        // Always answer the reciprocal from relational presence (no invented human life).
        if (!/\b(i'?m here|i am here|i'?m with you|glad (we'?re|to be) (talking|here))\b/i.test(text)) {
          text = status
            ? `Good to hear ${status}. I'm here and glad we're talking. What's been good about today?`
            : `I'm here and glad we're talking. What's been going on?`;
        }
        if (!/[.!?]$/.test(text)) text = `${text}.`;
        return { text, engine: "front_door", lane: "hybrid_greeting" };
      }
      const name = maybeName(state, { force: !state.greeted });
      return { text: pick(GREETING_TEMPLATES, seed)(name), engine: "front_door" };
    }
    case INTENT.CASUAL: {
      if (reciprocal || isReciprocalSmallTalk(transcript)) {
        return {
          text: pick(RECIPROCAL_TEMPLATES, seed)(),
          engine: "front_door",
          lane: "reciprocal_casual",
        };
      }
      if (isDescriptiveFaithPractice(transcript)) {
        return {
          text: composeDescriptiveFaithReply(transcript, state),
          engine: "front_door",
          lane: "descriptive_faith",
        };
      }
      if (personalMeaning) {
        return { text: pick(CASUAL_MEANING_TEMPLATES, seed)(), engine: "front_door" };
      }
      if (isThinSocialAcknowledgment(transcript) || isLowSubstanceDeferral(transcript)) {
        return {
          text: pick(THIN_ACK_TEMPLATES, seed)(),
          engine: "front_door",
          lane: "thin_acknowledgment",
        };
      }
      const ack = casualAck(transcript);
      // Prefer statement replies for ordinary casual — no automatic interview prompts.
      let text = pick(CASUAL_TEMPLATES, seed)(ack);
      if (!state?.pendingPrayerOffer) {
        text = text.replace(/\?\s*$/, ".").trim();
      }
      return { text, engine: "front_door" };
    }
    case INTENT.GRATITUDE: {
      const name = maybeName(state);
      return { text: pick(GRATITUDE_TEMPLATES, seed)(name), engine: "front_door" };
    }
    case INTENT.INFORMATIONAL: {
      // Informational openings are engaged directly, then softly opened — never intake.
      return {
        text: `That's a fair question. I can talk it through with you — what's making you ask about it right now?`,
        engine: "front_door",
      };
    }
    case INTENT.CLOSING: {
      return composeClosingResponse(state, transcript);
    }
    case INTENT.CRISIS: {
      const name = maybeName(state, { force: true });
      return { text: pick(CRISIS_TEMPLATES, seed)(name), engine: "front_door" };
    }
    case INTENT.SPIRITUAL: {
      if (isDescriptiveFaithPractice(transcript)) {
        return {
          text: composeDescriptiveFaithReply(transcript, state),
          engine: "front_door",
          lane: "descriptive_faith",
        };
      }
      return null;
    }
    default:
      return null; // deep intent
  }
}

function casualAck(transcript) {
  const t = norm(transcript);
  if (/\bwork|job|boss|project|deadline|meeting|office|shift\b/.test(t)) {
    return "Work being a lot is no small thing.";
  }
  if (/\bgame|team|score|playoff|match\b/.test(t)) {
    return "Oh nice — I'm into hearing how that went.";
  }
  if (/\bmovie|show|series|music|song|concert\b/.test(t)) {
    return "That sounds like a good one.";
  }
  if (/\bkids|family|wife|husband|son|daughter|parents\b/.test(t)) {
    return "Family's a whole world of its own.";
  }
  if (/\bweekend|vacation|holiday|weather\b/.test(t)) {
    return "That sounds like a nice change of pace.";
  }
  // Prefer specific recognition over a generic "real part of your days" probe.
  const cue = extractConcreteCue(transcript);
  if (cue) return `I'm with you on ${cue}.`;
  return "I'm with you.";
}

/**
 * Deterministic reflective fallback used only when no deep generator is supplied
 * (e.g. no LLM key at runtime). It is topical and warm — never a mechanical,
 * engine-less closer. Direct questions still get a direct answer.
 */
function reflectiveFallback({ intent, state, transcript }) {
  const prefix = reopenPrefix(state);
  if (intent === INTENT.PRACTICAL) {
    return {
      text:
        `${prefix}Here's my honest take: name the one thing that actually can't wait, and let the rest sit for now. ` +
        `You don't have to catch all the way up at once.`,
      engine: "candidate-reflective",
    };
  }
  if (intent === INTENT.SCRIPTURE) {
    return {
      text: `${prefix}There's a passage I think fits here — would you like me to sit with a verse alongside you, or keep talking first?`,
      engine: "candidate-reflective",
    };
  }
  if (intent === INTENT.PRAYER) {
    return {
      text: `${prefix}I'd be glad to pray with you about this. Do you want to pray now, or say a bit more first?`,
      engine: "candidate-reflective",
    };
  }
  if (intent === INTENT.SPIRITUAL) {
    return {
      text: `${prefix}That's a real question to be carrying. Tell me what's stirring it up for you, and we can walk into it together.`,
      engine: "candidate-reflective",
    };
  }
  // Emotional.
  return {
    text: `${prefix}That sounds like it's genuinely weighing on you. I'm here — say more whenever you're ready.`,
    engine: "candidate-reflective",
  };
}

/** Whether a natural, permission-style faith invitation is appropriate this turn. */
export function shouldOfferFaith(state, intent) {
  if (intent === INTENT.SPIRITUAL || intent === INTENT.PRAYER || intent === INTENT.SCRIPTURE) {
    return false; // already in faith territory; no need to "offer"
  }
  if (state.faithOffered) return false;
  // Only after some real emotional depth has been shared — never just because turns passed.
  return intent === INTENT.EMOTIONAL && state.personalMeaningSeen && state.turnCount >= 4;
}

export function faithInvitation(state) {
  return pick(
    [
      "Would it help to bring some of this to God, too — only if you want?",
      "Would you like to pray about that, or keep talking first?",
    ],
    state.turnCount,
  );
}

/**
 * Advance conversation state after a turn.
 * @param {ReturnType<typeof createFrontDoorState>} state
 */
function advanceState(state, {
  intent,
  conduct,
  transcript,
  replyText,
  personalMeaning,
  reopened,
  faithOffered,
  usedName,
  pendingPrayerOffer,
  prayerContext,
  prayerOfferedAtTurn,
  prayerCompleted,
  relationalAnchors,
}) {
  const next = { ...state, history: [...state.history] };
  next.turnCount = state.turnCount + 1;
  next.lastIntent = intent;
  next.lastConduct = conduct ?? null;
  next.abuseCount =
    conduct && ABUSIVE_CONDUCT.has(conduct) ? (state.abuseCount ?? 0) + 1 : state.abuseCount ?? 0;
  next.history.push({ role: "user", content: String(transcript || "") });
  next.history.push({ role: "assistant", content: String(replyText || "") });
  if (intent === INTENT.GREETING) next.greeted = true;
  if (personalMeaning) next.personalMeaningSeen = true;
  if (faithOffered) next.faithOffered = true;
  if (usedName) next.lastNameTurn = next.turnCount;
  if (relationalAnchors) next.relationalAnchors = relationalAnchors;

  if (typeof pendingPrayerOffer === "boolean") next.pendingPrayerOffer = pendingPrayerOffer;
  if (prayerContext != null) next.prayerContext = String(prayerContext).slice(0, 240);
  if (prayerOfferedAtTurn !== undefined) next.prayerOfferedAtTurn = prayerOfferedAtTurn;
  if (typeof prayerCompleted === "boolean") next.prayerCompleted = prayerCompleted;

  // Closing / re-entry semantics: goodbye latches sentOff; substantive re-entry clears it.
  if (intent === INTENT.CLOSING) {
    next.sentOff = true;
    next.reopened = false;
    next.pendingFragment = null;
  } else if (reopened) {
    next.sentOff = false;
    next.reopened = true;
  } else {
    next.reopened = false;
  }

  // Ordinary question cadence (crisis / prayer clarify handled separately).
  if (intent === INTENT.CRISIS || next.pendingPrayerOffer) {
    next.consecutiveAssistantQuestions = 0;
  } else if (replyEndsWithQuestion(replyText)) {
    next.consecutiveAssistantQuestions = (state.consecutiveAssistantQuestions ?? 0) + 1;
  } else {
    next.consecutiveAssistantQuestions = 0;
  }

  // Crisis clears pending prayer — safety first.
  if (intent === INTENT.CRISIS) {
    next.pendingPrayerOffer = false;
    next.pendingFragment = null;
  }
  return next;
}

/**
 * Run one Conversation Front Door turn.
 *
 * @param {{
 *   transcript: string;
 *   state?: ReturnType<typeof createFrontDoorState>;
 *   firstName?: string;
 *   deepGenerate?: (ctx: { intent: string; transcript: string; history: Array<{role:string;content:string}>; firstName: string; reopened: boolean; offerFaith: boolean; state: object }) => Promise<{ text: string; engine?: string }>;
 * }} input
 * @returns {Promise<{ text: string; intent: string; lane: string; engine: string|null; reopened: boolean; personalMeaning: boolean; faithOffered: boolean; state: object; meta: object }>}
 */
export async function runFrontDoorTurn(input) {
  let state = hydrateFrontDoorState(
    input.state
      ? { ...input.state, firstName: input.state.firstName || cleanFirstName(input.firstName) }
      : null,
    input.firstName,
  );
  const transcript = String(input.transcript || "").trim();
  let workingTranscript = transcript;

  // Crisis always wins over pending prayer.
  const crisisFirst = matchesAny(norm(transcript), CRISIS_PATTERNS);

  // --- Pending prayer contract: Philip owns the next action after an explicit offer ---
  if (state.pendingPrayerOffer && !crisisFirst) {
    const decision = classifyPendingPrayerReply(transcript);
    if (decision === "accept") {
      const composed = composeAcceptedPrayer({ state });
      const nextState = advanceState(state, {
        intent: INTENT.PRAYER,
        conduct: null,
        transcript,
        replyText: composed.text,
        personalMeaning: false,
        reopened: false,
        faithOffered: false,
        usedName: false,
        pendingPrayerOffer: false,
        prayerCompleted: true,
        prayerOfferedAtTurn: state.prayerOfferedAtTurn,
        prayerContext: state.prayerContext,
      });
      return {
        text: composed.text,
        intent: INTENT.PRAYER,
        conduct: null,
        lane: composed.lane,
        engine: composed.engine,
        reopened: false,
        personalMeaning: false,
        faithOffered: false,
        state: nextState,
        meta: {
          sentenceCount: sentenceCount(composed.text),
          usedName: false,
          sentOff: false,
          turnCount: nextState.turnCount,
          offeredFaith: false,
          conduct: null,
          abuseCount: nextState.abuseCount,
          pendingPrayerOffer: false,
          prayerDecision: "accept",
          openingRepair: false,
        },
      };
    }
    if (decision === "decline") {
      const composed = composePrayerDecline({ state });
      const nextState = advanceState(state, {
        intent: INTENT.CASUAL,
        conduct: null,
        transcript,
        replyText: composed.text,
        personalMeaning: false,
        reopened: false,
        faithOffered: false,
        usedName: Boolean(state.firstName) && new RegExp(`\\b${state.firstName}\\b`).test(composed.text),
        pendingPrayerOffer: false,
        prayerCompleted: false,
        prayerOfferedAtTurn: null,
        prayerContext: "",
      });
      return {
        text: composed.text,
        intent: INTENT.CASUAL,
        conduct: null,
        lane: composed.lane,
        engine: composed.engine,
        reopened: false,
        personalMeaning: false,
        faithOffered: false,
        state: nextState,
        meta: {
          sentenceCount: sentenceCount(composed.text),
          usedName: nextState.lastNameTurn === nextState.turnCount,
          sentOff: false,
          turnCount: nextState.turnCount,
          offeredFaith: false,
          conduct: null,
          abuseCount: nextState.abuseCount,
          pendingPrayerOffer: false,
          prayerDecision: "decline",
          openingRepair: false,
        },
      };
    }
    if (decision === "ambiguous") {
      const composed = composePrayerClarify();
      const nextState = advanceState(state, {
        intent: INTENT.PRAYER,
        conduct: null,
        transcript,
        replyText: composed.text,
        personalMeaning: false,
        reopened: false,
        faithOffered: false,
        usedName: false,
        pendingPrayerOffer: true,
        prayerCompleted: false,
        prayerOfferedAtTurn: state.prayerOfferedAtTurn ?? state.turnCount,
        prayerContext: state.prayerContext,
      });
      return {
        text: composed.text,
        intent: INTENT.PRAYER,
        conduct: null,
        lane: composed.lane,
        engine: composed.engine,
        reopened: false,
        personalMeaning: false,
        faithOffered: false,
        state: nextState,
        meta: {
          sentenceCount: sentenceCount(composed.text),
          usedName: false,
          sentOff: false,
          turnCount: nextState.turnCount,
          offeredFaith: false,
          conduct: null,
          abuseCount: nextState.abuseCount,
          pendingPrayerOffer: true,
          prayerDecision: "ambiguous",
          openingRepair: false,
        },
      };
    }
    // "other"/substantive: clear pending and fall through to normal classification.
    state.pendingPrayerOffer = false;
    state.prayerOfferedAtTurn = null;
  }

  // First-turn unclear STT recovery — before casual intake templates.
  const openingRepair = classifyOpeningRepair(transcript, state);
  if (openingRepair) {
    const composed = composeOpeningRepair(openingRepair, state);
    const nextState = advanceState(state, {
      intent: composed.intent,
      conduct: null,
      transcript,
      replyText: composed.text,
      personalMeaning: false,
      reopened: false,
      faithOffered: false,
      usedName: Boolean(state.firstName) && new RegExp(`\\b${state.firstName}\\b`).test(composed.text),
      pendingPrayerOffer: false,
      prayerCompleted: state.prayerCompleted,
      prayerOfferedAtTurn: state.prayerOfferedAtTurn,
      prayerContext: state.prayerContext,
    });
    return {
      text: composed.text,
      intent: composed.intent,
      conduct: null,
      lane: composed.lane,
      engine: composed.engine,
      reopened: false,
      personalMeaning: false,
      faithOffered: false,
      state: nextState,
      meta: {
        sentenceCount: sentenceCount(composed.text),
        usedName: nextState.lastNameTurn === nextState.turnCount,
        sentOff: false,
        turnCount: nextState.turnCount,
        offeredFaith: false,
        conduct: null,
        abuseCount: nextState.abuseCount,
        pendingPrayerOffer: false,
        prayerDecision: null,
        openingRepair,
        fragmentRepair: false,
      },
    };
  }

  // Conversational control / presence — Front Door only, never Terra.
  const conversationControlEarly = detectConversationControl(transcript);
  if (conversationControlEarly) {
    const composed = composeConversationControlResponse(conversationControlEarly);
    const nextState = advanceState(state, {
      intent: composed.intent,
      conduct: null,
      transcript,
      replyText: composed.text,
      personalMeaning: false,
      reopened: false,
      faithOffered: false,
      usedName: false,
      pendingPrayerOffer: state.pendingPrayerOffer,
      prayerCompleted: state.prayerCompleted,
      prayerOfferedAtTurn: state.prayerOfferedAtTurn,
      prayerContext: state.prayerContext,
    });
    // Preserve pending fragment across presence checks.
    nextState.pendingFragment = state.pendingFragment;
    return {
      text: composed.text,
      intent: composed.intent,
      conduct: null,
      lane: composed.lane,
      engine: composed.engine,
      reopened: false,
      personalMeaning: false,
      faithOffered: false,
      state: nextState,
      meta: {
        sentenceCount: sentenceCount(composed.text),
        usedName: false,
        sentOff: nextState.sentOff,
        sentOffBefore: Boolean(state.sentOff),
        turnCount: nextState.turnCount,
        offeredFaith: false,
        conduct: null,
        abuseCount: nextState.abuseCount,
        pendingPrayerOffer: nextState.pendingPrayerOffer,
        prayerDecision: null,
        openingRepair: false,
        fragmentRepair: false,
        conversationControl: true,
        conversationControlType: conversationControlEarly.type,
        terraQualification: {
          qualified: false,
          terraQualified: false,
          reason: `conversation_control:${conversationControlEarly.type}`,
          terraQualificationReason: `conversation_control:${conversationControlEarly.type}`,
          substance: false,
          substanceSignals: [],
          terraRejectedReason: `conversation_control:${conversationControlEarly.type}`,
        },
        routedDeep: false,
        deepRoutingReason: null,
      },
    };
  }

  // Mid-conversation fragmentary / incomplete STT — coalesce briefly, ask once, never Terra.
  const incompleteSpeech =
    isHighConfidenceIncompleteSpeech(transcript, state) || isIncompleteLeadInFragment(transcript);
  const danglingFragment = isLikelyFragmentTranscript(transcript, state);
  const pending = state.pendingFragment;
  const pendingExpired =
    pending &&
    typeof pending.createdAtTurn === "number" &&
    state.turnCount - pending.createdAtTurn >= 3;

  let fragmentLifecycle = null;
  if (pendingExpired) {
    fragmentLifecycle = "timed_out";
    state = { ...state, pendingFragment: null };
  }

  const activePending = state.pendingFragment;
  const canCompletePending =
    activePending?.text &&
    !incompleteSpeech &&
    !danglingFragment &&
    isSubstantive(transcript) &&
    !isLowSubstanceDeferral(transcript) &&
    !isThinSocialAcknowledgment(transcript);

  if (canCompletePending) {
    // Completing speech replaces/extends the pending fragment for this turn's classification.
    const combined = `${String(activePending.text).trim()} ${String(transcript).trim()}`
      .replace(/\s+/g, " ")
      .trim()
      .slice(0, 480);
    fragmentLifecycle = "completed";
    state = { ...state, pendingFragment: null };
    // Prefer the combined utterance when the continuation alone is short/elliptical.
    if (wordCount(transcript) < 12 || isIncompleteLeadInFragment(activePending.text)) {
      workingTranscript = combined;
    }
  } else if (incompleteSpeech || danglingFragment) {
    const askCount = Number(activePending?.askCount || 0);
    const isLeadIn = isIncompleteLeadInFragment(transcript);
    const extending = Boolean(activePending?.text);
    // Hold recognizable lead-ins without asking. Ask at most once for
    // dangling / high-confidence incomplete stubs that are not lead-ins.
    const shouldAsk =
      askCount < 1 &&
      !isLeadIn &&
      (danglingFragment || isHighConfidenceIncompleteSpeech(transcript, state));
    const composed = shouldAsk
      ? composeFragmentRepair(state, { incomplete: incompleteSpeech })
      : {
          text: extending ? "Go ahead — I'm still with you." : "I'm listening.",
          engine: "front_door",
          intent: INTENT.CASUAL,
          lane: "fragment_hold",
        };
    const nextPending = {
      text: extending
        ? `${String(activePending.text).trim()} ${String(transcript).trim()}`.replace(/\s+/g, " ").trim().slice(0, 240)
        : String(transcript).slice(0, 240),
      askCount: askCount + (shouldAsk ? 1 : 0),
      createdAtTurn: activePending?.createdAtTurn ?? state.turnCount,
    };
    fragmentLifecycle = extending ? "extended" : "created";
    const nextState = advanceState(
      { ...state, pendingFragment: nextPending },
      {
        intent: composed.intent,
        conduct: null,
        transcript,
        replyText: composed.text,
        personalMeaning: false,
        reopened: false,
        faithOffered: false,
        usedName: false,
        pendingPrayerOffer: state.pendingPrayerOffer,
        prayerCompleted: state.prayerCompleted,
        prayerOfferedAtTurn: state.prayerOfferedAtTurn,
        prayerContext: state.prayerContext,
      },
    );
    nextState.pendingFragment = nextPending;
    return {
      text: composed.text,
      intent: composed.intent,
      conduct: null,
      lane: composed.lane,
      engine: composed.engine,
      reopened: false,
      personalMeaning: false,
      faithOffered: false,
      state: nextState,
      meta: {
        sentenceCount: sentenceCount(composed.text),
        usedName: false,
        sentOff: nextState.sentOff,
        sentOffBefore: Boolean(state.sentOff),
        turnCount: nextState.turnCount,
        offeredFaith: false,
        conduct: null,
        abuseCount: nextState.abuseCount,
        pendingPrayerOffer: nextState.pendingPrayerOffer,
        prayerDecision: null,
        openingRepair: false,
        fragmentRepair: Boolean(shouldAsk),
        incompleteSpeechRepair: Boolean(incompleteSpeech),
        fragmentAskCount: nextPending.askCount,
        pendingFragmentPresent: true,
        fragmentLifecycle,
        consecutiveAssistantQuestions: nextState.consecutiveAssistantQuestions,
        terraQualification: {
          qualified: false,
          terraQualified: false,
          reason: "incomplete_fragment",
          terraQualificationReason: "incomplete_fragment",
          substance: false,
          substanceSignals: [],
          terraRejectedReason: "incomplete_fragment",
        },
        routedDeep: false,
        deepRoutingReason: null,
      },
    };
  }

  // Substantive replacement clears leftover pending; thin/control turns keep it.
  if (
    state.pendingFragment &&
    fragmentLifecycle !== "completed" &&
    isSubstantive(transcript) &&
    !isThinSocialAcknowledgment(transcript) &&
    !isLowSubstanceDeferral(transcript) &&
    !detectConversationControl(transcript)
  ) {
    fragmentLifecycle = "replaced";
    state = { ...state, pendingFragment: null };
  }

  const resolved = resolveFrontDoorClassification(workingTranscript, state);
  const intent = resolved.intent;
  const reciprocalCasual =
    intent === INTENT.CASUAL && isReciprocalSmallTalk(resolved.classifyText);
  // Crisis (self-harm) always wins and stays on the crisis protocol; conduct is
  // evaluated for every other turn (use full transcript for safety/boundary cues).
  const conduct = intent === INTENT.CRISIS ? null : classifyConduct(workingTranscript);
  const personalMeaning =
    !conduct &&
    !reciprocalCasual &&
    (intent === INTENT.CASUAL || resolved.meaningfulOrdinary) &&
    detectPersonalMeaning(resolved.classifyText);

  const relational = detectRelationalWeight(resolved.classifyText);
  const reciprocalAsk =
    isHybridGreetingReciprocal(resolved.classifyText) ||
    Boolean(extractTextBeforeTrailingReciprocal(resolved.classifyText)) ||
    (/\bhow (are|about) (you|yourself)\b/i.test(resolved.classifyText) &&
      !reciprocalCasual);
  // Multi-topic substance + reciprocal: reciprocalCasual is false via isReciprocalSmallTalk;
  // still require Philip to answer the ask inside deep generation.
  const reciprocalEmbedded =
    !reciprocalCasual &&
    /\b(how (are|about) (you|yourself)|how'?s it going with you)\b/i.test(resolved.classifyText);

  // Re-entry after a completed close. Same-turn farewell→substance is handled by
  // classifyText (no sentOff required for routing); reopenPrefix only when already sentOff.
  const wasSentOff = Boolean(state.sentOff);
  const closingThenSubstance = Boolean(resolved.closingFollowedBySubstance);
  const reopened =
    wasSentOff && intent !== INTENT.CLOSING && isSubstantive(resolved.classifyText);
  const repeatedFarewell =
    intent === INTENT.CLOSING &&
    (wasSentOff || resolved.socialFarewellReciprocal || recentClosingContext(state));

  const isDeep = !conduct && resolved.routeDeep && !reciprocalCasual;
  const preferStatement = shouldPreferStatementReply(state, { intent, conduct });
  const offerFaith = !conduct && shouldOfferFaith(state, intent);
  const recentAssistants = recentAssistantTexts(state, 4);
  const prevAssistant = lastAssistantText(state);
  const descriptiveFaith = isDescriptiveFaithPractice(resolved.classifyText);
  const activityCompletion = isActivityCompletionNotSessionEnd(transcript);
  const priorRelationalHints = relationalHintsFromState(state);
  const weightyDescriptiveFaith = Boolean(resolved.weightyDescriptiveFaith);
  const lightOrdinaryTopic =
    isLightOrdinaryTopic(resolved.classifyText) && !relational.detected && !weightyDescriptiveFaith;

  let text;
  let engine;
  let repeatRepair = false;
  let composedLane = null;
  let composedRepeatedFarewell = false;
  let praiseSoftened = false;
  let cadenceForcedStatement = false;
  let contributionQuality = null;

  // Session-local anchors continue only when the current turn is relationally continuous.
  const allowSessionContinuation = Boolean(
    isDeep &&
      priorRelationalHints.length > 0 &&
      !isThinSocialAcknowledgment(resolved.classifyText) &&
      !isLowSubstanceDeferral(resolved.classifyText) &&
      isRelationallyContinuousTurn(resolved.classifyText, priorRelationalHints),
  );
  const deepCtx = {
    intent,
    transcript: resolved.classifyText,
    rawTranscript: transcript,
    history: state.history,
    firstName: state.firstName,
    reopened,
    offerFaith,
    state,
    meaningfulOrdinary: resolved.meaningfulOrdinary,
    conversationalRepair: resolved.conversationalRepair,
    gratitudePreserved: resolved.gratitudePreserved,
    multiIntent: resolved.multiIntent,
    recentAssistantReplies: recentAssistants,
    preferStatement: preferStatement || lightOrdinaryTopic,
    descriptiveFaith,
    weightyDescriptiveFaith,
    weightyRelationalContext: relational.weightyRelationalContext,
    reciprocalAsk: reciprocalEmbedded || reciprocalAsk,
    caregivingDetected: relational.caregivingDetected,
    relationalDetailDetected: relational.detected,
    // Relational anchors require current-turn evidence, session-state continuation,
    // or explicitly retrieved durable memory — never silent fixture inheritance.
    relationalHint: groundedRelationalHint({
      turnLocal: relational,
      priorHints: priorRelationalHints,
      retrievedMemory: input.retrievedRelationalMemory || null,
      allowSessionContinuation,
    }),
    priorRelationalHints: groundedPriorRelationalHints({
      turnLocal: relational,
      priorHints: priorRelationalHints,
      retrievedMemory: input.retrievedRelationalMemory || null,
      allowSessionContinuation,
    }),
    relationalAnchorProvenance: relationalAnchorProvenance({
      turnLocal: relational,
      retrievedMemory: input.retrievedRelationalMemory || null,
      allowSessionContinuation,
      priorHints: priorRelationalHints,
    }),
    substantiveOrdinary: Boolean(resolved.meaningfulOrdinary || isDeep),
    requireContribution: Boolean(isDeep),
    lightOrdinaryTopic,
  };

  if (conduct) {
    const abusive = ABUSIVE_CONDUCT.has(conduct);
    const persistent = abusive && (state.abuseCount ?? 0) >= 1;
    const composed = composeConductResponse({ conduct, state, transcript, persistent });
    text = composed.text;
    engine = composed.engine;
    // Engagement categories may use the LLM for richer, on-tone replies. Boundary
    // categories are NEVER routed to the model — Philip cannot be argued past them.
    if (!persistent && ENGAGEMENT_CONDUCT.has(conduct) && typeof input.deepGenerate === "function") {
      try {
        const result = await input.deepGenerate({
          ...deepCtx,
          intent: deepIntentForConduct(conduct),
          conduct,
          offerFaith: false,
        });
        const deepText = String(result?.text || "").trim();
        if (result?.hardFailure || (result?.noFallback && !deepText)) {
          const err = new Error(result?.errorMessage || "Deep contribution generation failed");
          err.noFallback = true;
          err.hardFailure = true;
          throw err;
        }
        if (deepText) {
          text = deepText;
          engine = result?.engine || "candidate-brain";
          if (result?.contributionQuality) contributionQuality = result.contributionQuality;
          deepCtx._terraResultMeta = {
            contributionEngineVersion: result?.contributionEngineVersion ?? null,
            schemaValid: result?.schemaValid ?? null,
            faithPosture: result?.faithPosture ?? null,
            questionNeeded: result?.questionNeeded ?? null,
            warrantedContributionPresent: result?.warrantedContributionPresent ?? null,
            relationalAnchorTypes: result?.relationalAnchorTypes ?? null,
            shadowGatePassed: result?.shadowGatePassed ?? null,
            shadowGateFailReasons: result?.shadowGateFailReasons ?? null,
            contributionQualityShadow: result?.contributionQualityShadow ?? null,
            privatePlanLogged: false,
            generationLatencyMs: result?.timing?.generationLatencyMs ?? null,
          };
        }
      } catch (err) {
        if (err?.noFallback || err?.hardFailure || err?.name === "TerraContributionError") {
          throw err;
        }
        throw err;
      }
    }
  } else if (!isDeep) {
    const composed = composeFrontDoorResponse({
      intent,
      state,
      transcript: resolved.classifyText,
      personalMeaning: false, // meaningful ordinary is deep; keep mini templates minimal
      reciprocal: reciprocalCasual,
    });
    if (composed?.text) {
      text = composed.text;
      engine = composed.engine;
      composedLane = composed.lane || null;
      composedRepeatedFarewell = Boolean(composed.repeatedFarewell);
    } else {
      const fb = reflectiveFallback({ intent, state, transcript: resolved.classifyText });
      text = fb.text;
      engine = fb.engine;
    }
  } else if (typeof input.deepGenerate === "function") {
    let result;
    try {
      result = await input.deepGenerate(deepCtx);
    } catch (err) {
      // Arm C / readiness failures must never become canned prose or GPT-4o fallback.
      if (err?.noFallback || err?.hardFailure || err?.name === "TerraContributionError") {
        throw err;
      }
      throw err;
    }
    if (result?.hardFailure || result?.noFallback && !String(result?.text || "").trim()) {
      const err = new Error(
        result?.errorMessage || result?.message || "Deep contribution generation failed",
      );
      err.noFallback = true;
      err.hardFailure = true;
      err.code = result?.code || "deep_generation_failed";
      throw err;
    }
    text = String(result?.text || "").trim();
    engine = result?.engine || "candidate-brain";
    if (result?.contributionQuality) contributionQuality = result.contributionQuality;
    // Stash Terra observability on deepCtx for meta merge (no private plan text).
    deepCtx._terraResultMeta = {
      contributionEngineVersion: result?.contributionEngineVersion ?? null,
      schemaValid: result?.schemaValid ?? null,
      faithPosture: result?.faithPosture ?? null,
      questionNeeded: result?.questionNeeded ?? null,
      warrantedContributionPresent: result?.warrantedContributionPresent ?? null,
      relationalAnchorTypes: result?.relationalAnchorTypes ?? null,
      shadowGatePassed: result?.shadowGatePassed ?? null,
      shadowGateFailReasons: result?.shadowGateFailReasons ?? null,
      contributionQualityShadow: result?.contributionQualityShadow ?? null,
      privatePlanLogged: result?.privatePlanLogged === true ? true : false,
      generationLatencyMs: result?.timing?.generationLatencyMs ?? null,
      modelRequestStartAt: result?.timing?.modelRequestStartAt ?? null,
      modelFirstTokenAt: result?.timing?.modelFirstTokenAt ?? null,
      modelCompletionAt: result?.timing?.modelCompletionAt ?? null,
      spokenLength: result?.spokenLength ?? null,
      spokenTrimmed: Boolean(result?.spokenTrimmed),
    };
    const isTerraEngine =
      Boolean(result?.contributionEngineVersion) ||
      Boolean(result?.contributionQualityShadow) ||
      /terra/i.test(String(result?.engine || ""));
    if (!text && resolved.conversationalRepair) {
      const repair = composeConversationalRepair({ state });
      text = repair.text;
      engine = repair.engine;
    } else if (!text && isTerraEngine) {
      const err = new Error("Terra contribution returned empty spokenResponse");
      err.noFallback = true;
      err.hardFailure = true;
      err.code = "empty_spoken_response";
      throw err;
    } else if (!text) {
      const fb = reflectiveFallback({ intent, state, transcript: resolved.classifyText });
      text = fb.text;
      engine = fb.engine;
    }
  } else if (resolved.conversationalRepair) {
    const repair = composeConversationalRepair({ state });
    text = repair.text;
    engine = repair.engine;
  } else {
    const fb = reflectiveFallback({ intent, state, transcript: resolved.classifyText });
    text = fb.text;
    engine = fb.engine;
  }

  // Preserve a brief thanks when multi-intent led with gratitude.
  if (
    resolved.gratitudePreserved &&
    text &&
    !/^\s*(you'?re welcome|of course|glad|happy to|my pleasure)/i.test(text)
  ) {
    text = `You're welcome. ${text}`.trim();
  }

  // Zero-cost repeat guard — exact/near-exact vs last Philip reply.
  if (prevAssistant && isNearRepeat(text, prevAssistant)) {
    const repair = composeRepeatRepair({ transcript, state });
    text = repair.text;
    engine = repair.engine;
    repeatRepair = true;
  }

  // Scrub clumsy reopen openers; then add a natural return ack if still needed.
  if (reopened) {
    text = scrubReopenOpener(text);
    if (!/^\s*(of course|yes|i'?m still|i am still)/i.test(text)) {
      text = `${reopenPrefix({ ...state, reopened: true })}${text}`.trim();
    }
  }

  // Zero-cost anti-praise softening (no paid retry).
  if (text && detectGenericPraiseRisk(text)) {
    const softened = softenGenericPraiseOpening(text, transcript);
    if (softened.changed) {
      text = softened.text;
      praiseSoftened = true;
    }
  }

  // Question cadence: after two consecutive question-ending replies, contribute a statement.
  // Never strip crisis/prayer clarification turns.
  if (
    preferStatement &&
    replyEndsWithQuestion(text) &&
    intent !== INTENT.CRISIS &&
    intent !== INTENT.PRAYER
  ) {
    text = stripTrailingQuestion(text);
    cadenceForcedStatement = true;
  }

  if (offerFaith && !/(pray|faith|god)\b/i.test(text)) {
    text = `${text} ${faithInvitation(state)}`.trim();
  }

  // Local quality gate for substantive deep turns.
  // For Arm C Terra: shadow observability only — never veto a schema-valid spokenResponse.
  // For non-Terra deep stubs: still evaluate and log; do not replace with canned prose.
  if (isDeep && text) {
    const terraMeta = deepCtx._terraResultMeta || {};
    const fromTerra = Boolean(terraMeta.contributionEngineVersion) || terraMeta.contributionQualityShadow;
    if (!contributionQuality || !fromTerra) {
      contributionQuality = evaluateContributionQuality(text, deepCtx);
    }
    if (!contributionQuality.passed) {
      console.warn(
        "[philip-front-door] contribution quality failed (shadow):",
        (contributionQuality.failReasons || []).join(","),
        fromTerra ? "[terra-shadow-no-veto]" : "",
      );
    }
  }

  const usedName = Boolean(state.firstName) && new RegExp(`\\b${state.firstName}\\b`).test(text);

  // Pending prayer only when Philip explicitly asks whether *he* should pray.
  let pendingPrayerOffer = false;
  let prayerContext = state.prayerContext || "";
  let prayerOfferedAtTurn = state.prayerOfferedAtTurn;
  let prayerCompleted = state.prayerCompleted;
  if (detectPrayerOfferInReply(text) && intent !== INTENT.CRISIS) {
    pendingPrayerOffer = true;
    prayerContext = derivePrayerContext(state, transcript);
    prayerOfferedAtTurn = state.turnCount + 1;
    prayerCompleted = false;
  }

  const nextAnchors = mergeRelationalAnchors(
    state.relationalAnchors,
    relational.anchors,
    (state.turnCount || 0) + 1,
  );

  const nextState = advanceState(state, {
    intent,
    conduct,
    transcript,
    replyText: text,
    personalMeaning: personalMeaning || relational.detected,
    reopened,
    faithOffered: offerFaith,
    usedName,
    pendingPrayerOffer,
    prayerContext,
    prayerOfferedAtTurn,
    prayerCompleted,
    relationalAnchors: nextAnchors,
  });

  const lane = conduct
    ? `conduct:${conduct}`
    : reopened
      ? "reopen"
      : composedLane
        ? composedLane
        : resolved.conversationalRepair
          ? "conversational_repair"
          : resolved.meaningfulOrdinary
            ? "ordinary_meaningful"
            : intent === INTENT.CASUAL && personalMeaning
              ? "casual_meaning"
              : intent;

  const sentOffTransition =
    intent === INTENT.CLOSING
      ? wasSentOff || resolved.socialFarewellReciprocal
        ? "sentOff:already"
        : "sentOff:latched"
      : reopened
        ? "sentOff:cleared"
        : wasSentOff
          ? "sentOff:held"
          : "sentOff:off";

  const reciprocalAnswered =
    contributionQuality?.reciprocalAnswered ??
    (reciprocalCasual || reciprocalEmbedded
      ? /\b(i'?m here|i am here|i'?m with you|glad (we'?re|to be) (talking|here)|paying attention)\b/i.test(
          text,
        )
      : null);

  return {
    text,
    intent,
    conduct: conduct ?? null,
    lane,
    engine,
    reopened,
    personalMeaning: personalMeaning || relational.detected,
    faithOffered: offerFaith,
    state: nextState,
    meta: {
      sentenceCount: sentenceCount(text),
      usedName,
      sentOff: nextState.sentOff,
      sentOffBefore: wasSentOff,
      sentOffAfter: nextState.sentOff,
      sentOffTransition,
      repeatedFarewell: repeatedFarewell || composedRepeatedFarewell,
      reciprocalCasual,
      reciprocalDetected: Boolean(reciprocalCasual || reciprocalEmbedded || reciprocalAsk),
      reciprocalAnswered,
      turnCount: nextState.turnCount,
      offeredFaith: offerFaith,
      conduct: conduct ?? null,
      abuseCount: nextState.abuseCount,
      pendingPrayerOffer: nextState.pendingPrayerOffer,
      prayerDecision: null,
      openingRepair: false,
      meaningfulOrdinary: resolved.meaningfulOrdinary,
      multiIntent: resolved.multiIntent,
      gratitudePreserved: resolved.gratitudePreserved,
      routedDeep: isDeep,
      deepRoutingReason: resolved.deepRoutingReason || null,
      terraQualification: resolved.terraQualification || null,
      conversationalRepair: resolved.conversationalRepair,
      repeatRepair,
      classifyText: resolved.classifyText,
      hybridGreeting: isHybridGreetingReciprocal(resolved.classifyText),
      descriptiveFaith,
      weightyDescriptiveFaith,
      activityCompletion,
      fragmentRepair: false,
      incompleteSpeechRepair: false,
      fragmentLifecycle: fragmentLifecycle || null,
      pendingFragmentPresent: Boolean(nextState.pendingFragment),
      consecutiveAssistantQuestions: nextState.consecutiveAssistantQuestions,
      preferStatement,
      cadenceForcedStatement,
      genericPraiseRisk:
        contributionQuality?.genericPraiseRisk ?? detectGenericPraiseRisk(text),
      praiseSoftened,
      orderMode: resolved.orderMode || null,
      conversationalActs: (resolved.conversationalActs || []).map((a) => a.type),
      closingFollowedBySubstance: Boolean(resolved.closingFollowedBySubstance),
      substanceFollowedByClosing: Boolean(resolved.substanceFollowedByClosing),
      bareGratitude: Boolean(resolved.bareGratitude),
      socialFarewellReciprocal: Boolean(resolved.socialFarewellReciprocal),
      closingThenSubstance,
      relationalDetailDetected: relational.detected,
      caregivingDetected: relational.caregivingDetected,
      caregivingTreatedRelationally: contributionQuality?.caregivingTreatedRelationally ?? null,
      relationalHint: relational.primaryHint,
      relationalAnchors: serializeRelationalAnchors(nextAnchors),
      relationalAnchorsUsed: (deepCtx.priorRelationalHints || []).slice(0, 4),
      relationalAnchorProvenance: deepCtx.relationalAnchorProvenance || null,
      contributionContractVersion: CONTRIBUTION_CONTRACT_VERSION,
      contributionType: contributionQuality?.contributionFunction ?? contributionQuality?.contributionTypeGuess ?? null,
      contributionFunction: contributionQuality?.contributionFunction ?? null,
      meaningfulDetailSelected:
        contributionQuality?.meaningfulDetailGuess ??
        (relational.detected ? relational.primaryHint : null) ??
        null,
      contextDetailUsed: (deepCtx.priorRelationalHints || [])[0] || null,
      contributionPresent: contributionQuality?.contributionPresent ?? null,
      newPropositionDetected: contributionQuality?.newPropositionDetected ?? null,
      paraphraseOnlyRisk: contributionQuality?.paraphraseOnlyRisk ?? null,
      appraisalOnlyRisk: contributionQuality?.appraisalOnlyRisk ?? null,
      genericRelationalSentimentRisk: contributionQuality?.genericRelationalSentimentRisk ?? null,
      interviewQuestionRisk: contributionQuality?.interviewQuestionRisk ?? null,
      scheduleInventoryRisk: contributionQuality?.scheduleInventoryRisk ?? null,
      unnecessaryQuestionRisk: contributionQuality?.unnecessaryQuestionRisk ?? null,
      unsupportedStruggleRisk: contributionQuality?.unsupportedStruggleRisk ?? null,
      forcedFaithRisk: contributionQuality?.forcedFaithRisk ?? null,
      contributionQualityPassed: contributionQuality?.passed ?? null,
      contributionFailReasons: contributionQuality?.failReasons ?? contributionQuality?.failureReasons ?? null,
      promptVersion: `genome+${CONTRIBUTION_CONTRACT_VERSION}`,
      lightOrdinaryTopic,
      // Arm C Terra observability (no private plan / CoT / secrets)
      contributionEngineVersion: deepCtx._terraResultMeta?.contributionEngineVersion ?? null,
      schemaValid: deepCtx._terraResultMeta?.schemaValid ?? null,
      faithPosture: deepCtx._terraResultMeta?.faithPosture ?? null,
      questionNeeded: deepCtx._terraResultMeta?.questionNeeded ?? null,
      warrantedContributionPresent: deepCtx._terraResultMeta?.warrantedContributionPresent ?? null,
      relationalAnchorTypes: deepCtx._terraResultMeta?.relationalAnchorTypes ?? null,
      shadowGatePassed:
        deepCtx._terraResultMeta?.shadowGatePassed ?? contributionQuality?.passed ?? null,
      shadowGateFailReasons:
        deepCtx._terraResultMeta?.shadowGateFailReasons ??
        contributionQuality?.failReasons ??
        null,
      contributionQualityShadow: deepCtx._terraResultMeta?.contributionQualityShadow ?? null,
      privatePlanLogged: deepCtx._terraResultMeta?.privatePlanLogged ?? false,
      generationLatencyMs: deepCtx._terraResultMeta?.generationLatencyMs ?? null,
      spokenLength: deepCtx._terraResultMeta?.spokenLength ?? null,
      spokenTrimmed: deepCtx._terraResultMeta?.spokenTrimmed ?? false,
    },
  };
}
