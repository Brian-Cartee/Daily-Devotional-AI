/**
 * Philip Conversation Front Door.
 *
 * A deterministic conversational-intent layer that sits BEFORE emotional guidance.
 * It classifies what the user is actually doing (greeting, casual chat, a real
 * question, disclosure, faith, goodbye, crisis) and produces a natural, voice-shaped
 * response — answering or engaging the real topic before reaching for deeper meaning.
 *
 * Design goals (see PhilipCanon):
 *  - The first job is recognition, not intake. A greeting gets a greeting.
 *  - Answer before asking; a question is not required every turn.
 *  - Faith is offered, not forced. Scripture/prayer only when invited or accepted.
 *  - A goodbye may close warmly but must NEVER permanently disable generation.
 *    If the user speaks again with substance, Philip reopens and responds.
 *  - Use the person's name naturally and sparingly — never every turn.
 *
 * This module is intentionally free of network / LLM calls so it is fully
 * deterministic and testable at zero cost. Deep emotional/spiritual turns are
 * delegated to an injected `deepGenerate` adapter (a real LLM at runtime, a stub
 * in tests). When no adapter is supplied, a careful reflective fallback is used —
 * never a canned, engine-less dead end.
 */

