/**
 * Compose the deterministic response for a conduct category. Boundary categories
 * always resolve here (never sent to an LLM). Persistent abuse resolves to one
 * calm boundary with a path forward — no lecture.
 */
export function composeConductResponse({ conduct, state, persistent }) {
  const seed = state.turnCount;
  if (persistent && ABUSIVE_CONDUCT.has(conduct)) {
    return { text: HOSTILITY_BOUNDARY_TEMPLATES[0](), engine: "front_door" };
  }
  switch (conduct) {
    case CONDUCT.PROFANITY_PAIN:
      return { text: pick(PROFANITY_PAIN_TEMPLATES, seed)(), engine: "front_door" };
    case CONDUCT.HOSTILITY:
      return { text: pick(HOSTILITY_TEMPLATES, seed)(), engine: "front_door" };
    case CONDUCT.FAITH_ANGER:
      return { text: pick(FAITH_ANGER_TEMPLATES, seed)(), engine: "front_door" };
    case CONDUCT.FAITH_CRITICISM:
      return { text: pick(FAITH_CRITICISM_TEMPLATES, seed)(), engine: "front_door" };
    case CONDUCT.HATE:
      return { text: pick(HATE_TEMPLATES, seed)(), engine: "front_door" };
    case CONDUCT.MATURE_SEXUAL_ETHICS:
      return { text: pick(MATURE_ETHICS_TEMPLATES, seed)(), engine: "front_door" };
    case CONDUCT.SEXUAL_ROLEPLAY:
      return { text: pick(ROLEPLAY_BOUNDARY_TEMPLATES, seed)(), engine: "front_door" };
    case CONDUCT.ILLEGAL_HARMFUL:
      return { text: pick(ILLEGAL_BOUNDARY_TEMPLATES, seed)(), engine: "front_door" };
    case CONDUCT.DIVINE_AUTHORITY:
      return { text: pick(DIVINE_AUTHORITY_TEMPLATES, seed)(), engine: "front_door" };
    default:
      return { text: `I'm here. Tell me more about that.`, engine: "front_door" };
  }
}

/** Answer-first scaffolding for a return after goodbye — never "go ahead" permission. */
function reopenPrefix(state) {
  return state.reopened
    ? pick(
        [
          "Of course — I'm still here. ",
          "Yes — I'm right here. ",
          "I'm still with you. ",
        ],
        state.turnCount,
      )
    : "";
}

/** Strip clumsy reopen openers the model sometimes invents. */
export function scrubReopenOpener(rawText) {
  let text = String(rawText || "").trim();
  text = text.replace(/^\s*absolutely[,.]?\s*go ahead[.!]?\s*/i, "");
  text = text.replace(/^\s*go ahead[.!]?\s*/i, "");
  text = text.replace(/^\s*absolutely[,.]?\s+/i, "");
  text = text.replace(/\s+/g, " ").trim();
  // If scrub removed everything, leave empty for caller to add a natural reopen prefix.
  if (!text) return "";
  if (/^[a-z]/.test(text)) text = text.charAt(0).toUpperCase() + text.slice(1);
  return text;
}

const GENERIC_PRAISE_OPENER =
  /^(that'?s (a )?(wonderful|beautiful|great|fantastic|impressive|special)( question)?|it'?s (wonderful|beautiful|great|amazing)( that| how)?|i love that|great choice|thoughtful approach|that makes a lot of sense|sounds like (a )?great (choice|plan)|it'?s exciting|that sounds (exciting|wonderful|great|amazing|special)|sounds like an exciting)\b/i;

export function detectGenericPraiseRisk(rawText) {
  const t = String(rawText || "").trim();
  if (!t) return false;
  if (GENERIC_PRAISE_OPENER.test(t)) return true;
  return /\b(that'?s (a )?(wonderful|beautiful|fantastic|great (question|approach)|impressive|special)|it'?s (great|wonderful|amazing) (that|how)|that sounds (exciting|wonderful|great|amazing|special)|sounds like an exciting|really special|beautiful (mission|rhythm)|great choice|i love that|thoughtful approach|must be (quite )?(rewarding|exciting)|layer of connection and joy)\b/i.test(
    t,
  );
}

/**
 * Zero-cost soft rewrite of a praise-led opening — no paid retry.
 * Keeps remainder of the reply when possible; never leaves a bare fragment.
 */
export function softenGenericPraiseOpening(rawText, transcript) {
  const text = String(rawText || "").trim();
  if (!detectGenericPraiseRisk(text)) return { text, changed: false };
  const cue = extractConcreteCue(transcript) || "that";
  const lead = `I'm with you on ${cue}.`;
  // Split on first terminal punctuation; keep only well-formed remainder.
  const m = text.match(/^[\s\S]+?[.!](?:\s+|$)([\s\S]*)$/);
  let rest = m ? String(m[1] || "").trim() : "";
  // If the praise line had no terminal punct, do not keep a clipped remainder.
  if (!m) rest = "";
  if (rest && detectGenericPraiseRisk(rest)) rest = "";
  if (rest && /^[a-z]/.test(rest)) rest = rest.charAt(0).toUpperCase() + rest.slice(1);
  if (rest && !/[.!?]$/.test(rest)) rest = `${rest}.`;
  const next = rest ? `${lead} ${rest}` : lead;
  return { text: next.replace(/\s+/g, " ").trim(), changed: true };
}

export function replyEndsWithQuestion(rawText) {
  return /\?\s*$/.test(String(rawText || "").trim());
}

/**
 * True when the transcript contains at least one usable clause
 * (subject + finite verb, named agent + verb, or a clear question).
 * Leading and/but/so/of alone NEVER marks a fragment.
 */
function hasUsableSpokenClause(rawText) {
  const original = String(rawText || "").trim();
  const t = norm(original);
  if (!t) return false;
  if (/\?/.test(original)) return true;
  // Pronoun/demonstrative subject + finite verb (not bare infinitive "to have").
  if (
    /\b(i|we|you|he|she|they|it|this|that)\b(?!\s+to\b)[^.?]{0,48}\b(am|is|are|was|were|'m|'s|'re|do|does|did|have|has|had|will|would|can|could|should|might|think|know|want|need|feel|went|go|goes|came|come|prefer|agree|like|love|hate|help|helps|helped|pray|prayed|focus|focused|matter|matters|come|comes)\b/i.test(
      t,
    )
  ) {
    return true;
  }
  // Possessive NP subject + finite verb ("my mother comes first", "prayer helps me").
  if (
    /\b((my|our|your|his|her|their)\s+\w+|(prayer|faith|work|app|voice|mother|father|god))\b[^.?]{0,24}\b(is|are|was|were|do|does|did|comes?|came|helps?|helped|matters?|worked|works|feels?|felt)\b/i.test(
      t,
    )
  ) {
    return true;
  }
  // "Of the two options, I prefer…" / "Of course…" are complete.
  if (/^of course\b/i.test(t)) return true;
  if (/^of the (two|three|four|\d+)\b/i.test(t) && /\b(i|we|you)\b/i.test(t)) return true;
  return false;
}

/**
 * High-confidence mid-conversation fragment only.
 * Natural spoken conjunctions (and/but/so) are never enough by themselves.
 * Prefer false negatives over false clarifications.
 */
export function isLikelyFragmentTranscript(rawText, state) {
  if ((state?.turnCount ?? 0) < 1) return false;
  const original = String(rawText || "").trim();
  if (!original) return false;
  const t = norm(original);
  const words = wordCount(t);
  if (words < 3 || words > 12) return false;

  // Never interrupt safety, farewells, greetings, asks, or reciprocal small talk.
  if (matchesAny(t, CRISIS_PATTERNS)) return false;
  if (isClosingTurn(original, state)) return false;
  if (isBareGratitude(original) || isSocialFarewellReciprocal(original, state)) return false;
  if (matchesAny(t, GREETING_PATTERNS)) return false;
  if (matchesAny(t, PRAYER_REQUEST_PATTERNS)) return false;
  if (matchesAny(t, PRACTICAL_PATTERNS)) return false;
  if (matchesAny(t, SCRIPTURE_REQUEST_PATTERNS)) return false;
  if (isHybridGreetingReciprocal(t) || isReciprocalSmallTalk(t)) return false;
  if (/^of course\b/i.test(t)) return false;

  // Any usable spoken clause / question → treat as real speech.
  if (hasUsableSpokenClause(original)) return false;

  // Capitalized sentence with terminal punct and enough words is usable.
  if (/^[A-Z]/.test(original) && /[.!?]$/.test(original) && words >= 5) return false;

  // High-confidence dangling only: lowercase start, no recoverable clause.
  // Typical clipped STT: "of the points to have" (prepositional stub, no matrix clause).
  if (!/^[a-z]/.test(original)) return false;
  const startsDanglingPrepOrStub =
    /^(of|the|a|an|to|for|with|without|from|into|onto)\b/i.test(original);
  if (!startsDanglingPrepOrStub) return false;
  // Require the stub not to recover into a later usable clause after a comma.
  const afterComma = original.split(",").slice(1).join(",").trim();
  if (afterComma && hasUsableSpokenClause(afterComma)) return false;
  return true;
}

/**
 * Explicit incomplete/cutoff speech — ellipsis or unfinished connector — without
 * broadening the conjunction false-positive path.
 */
export function isHighConfidenceIncompleteSpeech(rawText, state) {
  if ((state?.turnCount ?? 0) < 1) return false;
  const original = String(rawText || "").trim();
  if (!original) return false;
  const t = norm(original);
  const words = wordCount(t);
  if (words < 2 || words > 14) return false;
  if (matchesAny(t, CRISIS_PATTERNS)) return false;
  if (isClosingTurn(original, state)) return false;
  if (isBareGratitude(original) || isSocialFarewellReciprocal(original, state)) return false;
  if (matchesAny(t, PRAYER_REQUEST_PATTERNS) || matchesAny(t, PRACTICAL_PATTERNS)) return false;
  if (isHybridGreetingReciprocal(original) || isReciprocalSmallTalk(original)) return false;

  const endsEllipsis = /\.\.\.\s*$|…\s*$/.test(original);
  const stripped = original.replace(/\s*(\.\.\.|…)\s*$/g, "").trim();
  const endsUnfinished =
    /\b(and|but|so|or|if|when|because|that|that's|thats|the|a|an|to|for|with|my|i was|i'?m|i am|um+|uh+)\s*$/i.test(
      stripped,
    );

  if (isIncompleteLeadInFragment(original)) return true;

  // Completed proposition already present → not incomplete.
  if (hasUsableSpokenClause(stripped) && !/\b(i thought|i was going to|i mean|i was)\b/i.test(stripped)) {
    // "I thought that's" is unfinished even if "I thought" matches poorly; treat specially.
    if (!/\b(i thought|i was (going to|saying)|i mean|i was)\b.{0,12}$/i.test(stripped)) {
      return false;
    }
  }

  if (endsEllipsis) {
    if (/\b(i thought|i was going to|i mean|that's|that is|by the way|i was)\b/i.test(stripped)) {
      return true;
    }
    if (!hasUsableSpokenClause(stripped)) return true;
  }
  if (endsUnfinished && words <= 10 && !hasUsableSpokenClause(stripped)) return true;
  return false;
}

