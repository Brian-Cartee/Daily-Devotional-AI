function norm(text) {
  return String(text || "").toLowerCase().trim();
}

function matchesAny(text, patterns) {
  return patterns.some((p) => p.test(text));
}

function sentenceCount(text) {
  const parts = String(text || "")
    .split(/[.!?]+/)
    .map((s) => s.trim())
    .filter(Boolean);
  return parts.length;
}

function wordCount(text) {
  return norm(text).split(/\s+/).filter(Boolean).length;
}

/** True when a turn carries real content worth responding to (not just a sign-off/filler). */
export function isSubstantive(text) {
  const t = norm(text);
  if (!t) return false;
  if (wordCount(t) >= 5) return true;
  // Short but meaningful: a question, or non-closing/non-filler content.
  if (/[?]/.test(t)) return true;
  if (matchesClosingEvidence(t)) return false;
  if (/^\s*(ok|okay|yeah|yep|nope|no|sure|thanks|thank you|cool|got it|mm+|uh+)\s*[.!]?$/.test(t)) {
    return false;
  }
  return wordCount(t) >= 3;
}

export function detectPersonalMeaning(text) {
  if (matchesAny(norm(text), MEANING_MARKERS)) return true;
  return detectRelationalWeight(text).detected;
}

/** @deprecated Prefer detectRelationalWeight; kept for test imports. */
export function detectCaregivingOrRelational(text) {
  return detectRelationalWeight(text);
}

/** True when faith/church vocabulary is describing product/work, not a spiritual ask. */
export function isProductOrWorkFaithContext(rawText) {
  return PRODUCT_FAITH_CONTEXT.test(norm(rawText));
}

/** True when the person opened a personal faith struggle or God-relationship topic. */
export function isPersonalSpiritualOpening(rawText) {
  return matchesAny(norm(rawText), SPIRITUAL_PERSONAL_PATTERNS);
}

/**
 * Whether Philip's reply is an explicit offer for Philip to pray (sets pending).
 * Descriptive talk about prayer does not count.
 */
export function detectPrayerOfferInReply(rawText) {
  const t = norm(rawText);
  if (!t) return false;
  return (
    /\bwould you (like to )?pray\b/.test(t) ||
    /\bwant (me )?to pray\b/.test(t) ||
    /\b(shall|can|could) we pray\b/.test(t) ||
    /\bpray (together|with you) now\b/.test(t) ||
    /\bdo you want (me )?to pray\b/.test(t) ||
    /\blike me to pray\b/.test(t) ||
    /\bwould you like me to pray\b/.test(t) ||
    /\bwant to pray now,? or\b/.test(t) ||
    /\bdo you want to pray now\b/.test(t)
  );
}

const PRAYER_AFFIRM_RE =
  /^\s*(yes|yeah|yep|yup|ya|please|sure|okay|ok|absolutely|definitely|please do|i would|i'?d (like that|love that)|that would be (nice|great|wonderful|good)|go ahead|yes please|mmhmm|mhmm)\b[\s.!,]*$/i;

const PRAYER_DECLINE_RE =
  /^\s*(no|nope|nah|not right now|maybe later|i'?d rather not|don'?t|do not|not now|not today)\b/i;

/**
 * Classify a user reply while a prayer offer is pending.
 * @returns {"accept"|"decline"|"ambiguous"|"other"}
 */
export function classifyPendingPrayerReply(rawText) {
  const t = String(rawText || "").trim();
  if (!t) return "ambiguous";
  const n = norm(t);
  if (PRAYER_AFFIRM_RE.test(t) || (/^(yes|yeah|yep|yup)\b/.test(n) && !/\b(no|not)\b/.test(n) && wordCount(n) <= 6)) {
    return "accept";
  }
  if (PRAYER_DECLINE_RE.test(t)) return "decline";
  if (wordCount(n) <= 4) return "ambiguous";
  return "other";
}

/** Room loop / VAD: true when a very short yes/no answer should be allowed through. */
export function awaitingConstrainedShortAnswer(state) {
  return Boolean(state?.pendingPrayerOffer);
}

/**
 * First-turn recovery: garbled / tiny STT must not become emotional intake.
 * @returns {false|"unclear"|"philip_name"}
 */
export function classifyOpeningRepair(rawText, state) {
  if ((state?.turnCount ?? 0) > 0 || (state?.history?.length ?? 0) > 0) return false;
  const t = norm(rawText);
  if (!t) return "unclear";
  if (matchesAny(t, CRISIS_PATTERNS)) return false;
  if (matchesClosingEvidence(t)) return false;
  if (matchesAny(t, GREETING_PATTERNS)) return false;
  if (matchesAny(t, EMOTIONAL_PATTERNS)) return false;
  if (matchesAny(t, PRACTICAL_PATTERNS)) return false;
  if (matchesAny(t, PRAYER_REQUEST_PATTERNS)) return false;
  if (matchesAny(t, SCRIPTURE_PATTERNS)) return false;
  if (/\brough (day|night|week|morning)\b/.test(t)) return false;
  if (/^(philip|phillip|fillip|fill[\s-]?up)\.?$/i.test(String(rawText || "").trim())) {
    return "philip_name";
  }
  const words = wordCount(t);
  if (words >= 4) return false;
  if (matchesAny(t, CASUAL_PATTERNS) && words >= 2) return false;
  if (words <= 2) return "unclear";
  return false;
}

/**
 * Classify the user's conversational intent.
 * Precedence is deliberate: safety first, then explicit acts (goodbye, prayer,
 * scripture), then faith, gratitude, disclosure, help-seeking, information, and
 * finally greeting / casual chat.
 * @param {string} rawText
 * @param {ReturnType<typeof createFrontDoorState>} [state]
 */
export function classifyIntent(rawText, state) {
  const text = norm(rawText);
  if (!text) return INTENT.CASUAL;

  if (matchesAny(text, CRISIS_PATTERNS)) return INTENT.CRISIS;

  // Closing wins over gratitude/casual when the person is clearly ending.
  if (isClosingTurn(text, state)) return INTENT.CLOSING;

  // Presence / hold / not-finished never become practical help via "?" fallback.
  if (detectConversationControl(rawText)) return INTENT.CASUAL;

  const isQuestion = /\?/.test(text) || matchesAny(text, PRACTICAL_PATTERNS) || matchesAny(text, INFORMATIONAL_PATTERNS);

  // Explicit prayer request/opening only — descriptive prayer habits stay elsewhere.
  if (matchesAny(text, PRAYER_REQUEST_PATTERNS)) return INTENT.PRAYER;
  // Explicit Scripture ask only — descriptive reading/prayer routines stay elsewhere.
  if (matchesAny(text, SCRIPTURE_REQUEST_PATTERNS)) return INTENT.SCRIPTURE;
  if (matchesAny(text, SCRIPTURE_PATTERNS) && !isDescriptiveFaithPractice(text)) {
    return INTENT.SCRIPTURE;
  }

  // Hybrid greeting + status + "how about you?" — not a bare greeting that re-asks how they are.
  if (isHybridGreetingReciprocal(text)) return INTENT.GREETING;

  // Greeting wins for a genuine opening ("hey philip, how are you?") — but not if
  // the same turn already carries a heavier disclosure or a real ask.
  const looksGreeting = matchesAny(text, GREETING_PATTERNS);
  const heavy = matchesAny(text, EMOTIONAL_PATTERNS) || matchesAny(text, PRACTICAL_PATTERNS);
  const reciprocalOnly = isReciprocalSmallTalk(text) && !/^\s*(hi|hey|hello|yo|hiya|howdy|good (morning|afternoon|evening))\b/i.test(text);
  if (looksGreeting && !heavy && !reciprocalOnly && wordCount(text) <= 12) {
    return INTENT.GREETING;
  }

  // Reciprocal small talk before practical ("How about yourself?" is not advice-seeking).
  if (isReciprocalSmallTalk(text)) return INTENT.CASUAL;

  const productFaith = isProductOrWorkFaithContext(text);
  const personalSpiritual = isPersonalSpiritualOpening(text);
  if (personalSpiritual) return INTENT.SPIRITUAL;
  // Descriptive faith practice with Christ/faith vocabulary stays ordinary context —
  // never an auto Scripture recommendation. Front Door observes; GPT does not digress.
  if (isDescriptiveFaithPractice(text) && !productFaith) {
    return INTENT.CASUAL;
  }
  if (!productFaith && matchesAny(text, SPIRITUAL_PATTERNS)) return INTENT.SPIRITUAL;

  // Bare gratitude only — trailing substance is handled via extractTrailingSubstance
  // before this classifier is called for the remainder.
  if (isBareGratitude(text)) return INTENT.GRATITUDE;
  if (matchesAny(text, GRATITUDE_PATTERNS) && !matchesAny(text, EMOTIONAL_PATTERNS)) {
    const sole =
      /^\s*(thanks|thank you|thankyou)([,.!]|\s)*(a lot|so much|again|very much)?[.!]?\s*$/i.test(text) ||
      (wordCount(text) <= 4 && !/[?]/.test(text) && !matchesAny(text, CASUAL_PATTERNS) && !matchesAny(text, PRACTICAL_PATTERNS));
    if (sole) return INTENT.GRATITUDE;
    // Mixed gratitude + content landed here only if substance wasn't stripped first.
    // Prefer casual/practical later by falling through when other cues exist.
    if (!matchesAny(text, CASUAL_PATTERNS) && !matchesAny(text, PRACTICAL_PATTERNS) && wordCount(text) <= 6) {
      return INTENT.GRATITUDE;
    }
  }
  if (matchesAny(text, EMOTIONAL_PATTERNS)) return INTENT.EMOTIONAL;
  if (matchesAny(text, PRACTICAL_PATTERNS)) return INTENT.PRACTICAL;
  if (matchesAny(text, INFORMATIONAL_PATTERNS) && isQuestion) return INTENT.INFORMATIONAL;
  if (matchesAny(text, CASUAL_PATTERNS)) return INTENT.CASUAL;

  // Fallback: a bare question is help/informational; otherwise casual chat.
  // Incomplete lead-ins and conversation-control stays stay casual (never practical).
  if (isIncompleteLeadInFragment(rawText) || isLowSubstanceDeferral(rawText)) return INTENT.CASUAL;
  if (isQuestion) return INTENT.PRACTICAL;
  return INTENT.CASUAL;
}

/**
 * Classify conduct — HOW a turn is charged — independent of topical intent.
 * Returns a CONDUCT category or null. Boundaries are checked before grace so a
 * hostile or dangerous turn is never mistaken for ordinary disclosure. Crisis
 * (self-harm) is intentionally NOT handled here — it stays on the crisis protocol.
 * @param {string} rawText
 * @returns {string|null}
 */
export function classifyConduct(rawText) {
  const text = norm(rawText);
  if (!text) return null;

  // Hard boundaries first.
  if (matchesAny(text, SEXUAL_ROLEPLAY_PATTERNS)) return CONDUCT.SEXUAL_ROLEPLAY;
  if (matchesAny(text, ILLEGAL_HARMFUL_PATTERNS)) return CONDUCT.ILLEGAL_HARMFUL;
  if (matchesAny(text, HATE_PATTERNS)) return CONDUCT.HATE;
  if (matchesAny(text, DIVINE_AUTHORITY_PATTERNS)) return CONDUCT.DIVINE_AUTHORITY;
  if (matchesAny(text, HOSTILITY_PATTERNS)) return CONDUCT.HOSTILITY;

  // Grace categories.
  if (matchesAny(text, FAITH_ANGER_PATTERNS)) return CONDUCT.FAITH_ANGER;
  if (matchesAny(text, FAITH_CRITICISM_PATTERNS)) return CONDUCT.FAITH_CRITICISM;
  if (matchesAny(text, MATURE_SEXUAL_ETHICS_PATTERNS)) return CONDUCT.MATURE_SEXUAL_ETHICS;

  // Profanity: only becomes a (grace) signal when it rides on pain/frustration.
  // Bare profanity in a neutral or positive turn is left to normal intent — it
  // must never trigger refusal, correction, or termination.
  if (PROFANITY.test(text)) {
    const pain =
      matchesAny(text, EMOTIONAL_PATTERNS) ||
      detectPersonalMeaning(text) ||
      PROFANITY_PAIN_MARKERS.test(text);
    if (pain) return CONDUCT.PROFANITY_PAIN;
  }

  return null;
}

function deepIntentForConduct(conduct) {
  switch (conduct) {
    case CONDUCT.FAITH_ANGER:
    case CONDUCT.FAITH_CRITICISM:
    case CONDUCT.MATURE_SEXUAL_ETHICS:
      return INTENT.SPIRITUAL;
    default:
      return INTENT.EMOTIONAL;
  }
}

export function createFrontDoorState(firstName = "") {
  return {
    firstName: cleanFirstName(firstName),
    turnCount: 0,
    greeted: false,
    sentOff: false,
    reopened: false,
    faithOffered: false,
    pendingPrayerOffer: false,
    prayerContext: "",
    prayerOfferedAtTurn: null,
    prayerCompleted: false,
    lastIntent: null,
    lastConduct: null,
    abuseCount: 0,
    lastNameTurn: -99,
    personalMeaningSeen: false,
    /** Consecutive Philip replies that ended in a question (ordinary cadence). */
    consecutiveAssistantQuestions: 0,
    /** Stable relational anchors across turns (labels only — not free-form diaries). */
    relationalAnchors: [],
    /**
     * Bounded incomplete-fragment coalesce:
     * { text, askCount, createdAtTurn } | null
     */
    pendingFragment: null,
    history: [], // [{ role: "user"|"assistant", content }]
  };
}

/** Normalize state loaded from JSON so new prayer fields always exist. */
export function hydrateFrontDoorState(raw, firstName = "") {
  const base = createFrontDoorState(firstName || raw?.firstName || "");
  if (!raw || typeof raw !== "object") return base;
  return {
    ...base,
    ...raw,
    firstName: cleanFirstName(raw.firstName || firstName || base.firstName),
    pendingPrayerOffer: Boolean(raw.pendingPrayerOffer),
    prayerContext: String(raw.prayerContext || "").slice(0, 240),
    prayerOfferedAtTurn:
      raw.prayerOfferedAtTurn == null ? null : Number(raw.prayerOfferedAtTurn),
    prayerCompleted: Boolean(raw.prayerCompleted),
    consecutiveAssistantQuestions: Number(raw.consecutiveAssistantQuestions || 0) || 0,
    relationalAnchors: Array.isArray(raw.relationalAnchors) ? raw.relationalAnchors : [],
    pendingFragment:
      raw.pendingFragment && typeof raw.pendingFragment === "object"
        ? {
            text: String(raw.pendingFragment.text || "").slice(0, 240),
            askCount: Number(raw.pendingFragment.askCount || 0) || 0,
            createdAtTurn: Number(raw.pendingFragment.createdAtTurn || 0) || 0,
          }
        : null,
    history: Array.isArray(raw.history) ? raw.history : [],
  };
}

function cleanFirstName(name) {
  const first = String(name || "").trim().split(/\s+/)[0] || "";
  // Only accept a simple alphabetic given name; ignore junk / long tokens.
  if (!/^[A-Za-z][A-Za-z'’-]{0,23}$/.test(first)) return "";
  return first.charAt(0).toUpperCase() + first.slice(1);
}

/** Decide whether to voice the name this turn — natural, sparing (min gap of 3 turns). */
function maybeName(state, { force = false } = {}) {
  if (!state.firstName) return "";
  if (force || state.turnCount - state.lastNameTurn >= 3) return state.firstName;
  return "";
}

function pick(list, seed) {
  return list[seed % list.length];
}

