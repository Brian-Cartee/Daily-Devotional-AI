/** Continuations that keep a leave-taking "go"/"run" phrase as session farewell. */
const LEAVE_TAKING_CONTINUATION =
  /\b(reconnect|connect|talk|speak|catch up|come back|later|soon|again|take care|bye|goodbye|good ?night|this (afternoon|evening|morning)|tonight|tomorrow)\b/i;

/**
 * "We can talk about the match later" is topical deferral — not session leave-taking.
 */
export function isTopicalTalkLaterNotSessionClose(rawText) {
  const t = norm(rawText);
  if (!t) return false;
  if (isGoPhraseSessionFarewell(t)) return false;
  if (/\b(goodbye|good ?bye|bye\b|take care|sign off|heading out|got to go|gotta go|need to go|have to go|got to run|gotta run|need to run|have to run)\b/i.test(t)) {
    return false;
  }
  if (/\b(can we|could we|let'?s) (reconnect|connect)\b/i.test(t)) return false;
  // Explicit reconnect invites still close even with "about".
  if (/\b(reconnect|connect) (later|soon|again)\b/i.test(t) && !/\btalk about\b/i.test(t)) {
    return false;
  }
  return (
    /\b(talk|speak|chat) about\b.{0,48}\b(later|soon|tomorrow)\b/i.test(t) ||
    /\b(we can|we'?ll|i'?ll) (talk|speak|chat) about\b/i.test(t)
  );
}

/** After "got/have/need to run", these tails are activity — not hang-up. */
function runRemainderIsActivityPurpose(after) {
  const r = String(after || "")
    .trim()
    .replace(/^[\s,;:.—–\-]+/, "");
  if (!r) return false;
  if (/^(an?\s+)?(errand|mile|miles|lap|race|marathon|drill|play|route|loop)\b/i.test(r)) return true;
  if (/^(through|over|into|up|down|across|by|past)\b/i.test(r)) return true;
  if (/^(for a |some )?(run|jog|sprint|workout)\b/i.test(r)) return true;
  if (LEAVE_TAKING_CONTINUATION.test(r)) return false;
  if (/^(but|and|so|though|however)\b/i.test(r)) {
    if (LEAVE_TAKING_CONTINUATION.test(r)) return false;
    const afterConj = r
      .replace(/^(but|and|so|though|however)\b/i, "")
      .trim()
      .replace(/^[\s,;:.—–\-]+/, "");
    return runRemainderIsActivityPurpose(afterConj) || goRemainderIsActivityPurpose(afterConj);
  }
  return goRemainderIsActivityPurpose(r);
}

/**
 * Remainder after a leave-taking "go" cue that indicates destination/purpose/activity,
 * not conversational hang-up.
 */
function goRemainderIsActivityPurpose(after) {
  let r = String(after || "").trim().replace(/^[\s,;:.—–\-]+/, "");
  if (!r) return false;

  // Explicit leave-taking tails.
  if (/^(for now|for today)[.!]?\s*$/i.test(r)) return false;
  if (/^(now|then)[.!]?\s*$/i.test(r)) return false;

  // "go deeper / go back / go ahead / go through" — topical continuation, not hang-up.
  if (/^(deeper|back|ahead|forward|through|further)\b/i.test(r)) return true;

  // Peel time-box "for now" / "for today" before the generic for/to activity rule.
  // "I need to go for now, but can we reconnect later?" stays farewell.
  if (/^(for now|for today)\b/i.test(r)) {
    const afterBox = r
      .replace(/^(for now|for today)\b/i, "")
      .trim()
      .replace(/^[\s,;:.—–\-]+/, "");
    if (!afterBox) return false;
    if (/^(but|and|so|though|however)\b/i.test(afterBox)) {
      if (LEAVE_TAKING_CONTINUATION.test(afterBox)) return false;
      const afterConj = afterBox
        .replace(/^(but|and|so|though|however)\b/i, "")
        .trim()
        .replace(/^[\s,;:.—–\-]+/, "");
      return goRemainderIsActivityPurpose(afterConj);
    }
    if (LEAVE_TAKING_CONTINUATION.test(afterBox)) return false;
    return goRemainderIsActivityPurpose(afterBox);
  }

  if (/^(now|then)\b/i.test(r)) {
    // Peel "now"/"then" plus separators (space or dash/punct). Require progress
    // so "now—hiking" does not recurse forever when whitespace-only strip fails.
    const peeled = r.replace(/^(now|then)(?:[\s,;:.—–\-]+|$)/i, "");
    if (peeled === r) return false;
    const afterNow = peeled.trim().replace(/^[\s,;:.—–\-]+/, "");
    if (!afterNow || /^(for now|for today)[.!]?\s*$/i.test(afterNow)) return false;
    if (LEAVE_TAKING_CONTINUATION.test(afterNow)) return false;
    if (/^(to|for|and|with|over|into|onto)\b/i.test(afterNow)) return true;
    if (goRemainderIsActivityPurpose(afterNow)) return true;
    // "now — talk later" is still leave-taking (handled by talk-later elsewhere).
    return false;
  }

  // Purpose / destination / accompaniment / forthcoming activity.
  if (
    /^(for|to|with|over|into|onto|toward|towards|and|do|make|watch|pick|get|see|meet|run|grab|check|help|visit|buy|take|join)\b/i.test(
      r,
    )
  ) {
    return true;
  }
  // Bare activity gerunds: "going to go hiking"
  if (/^(hiking|walking|running|swimming|shopping|skiing|jogging|climbing)\b/i.test(r)) {
    return true;
  }
  return false;
}

/**
 * Leave-taking that may include a soft reconnect ask ("can we talk later?").
 * Does not match topical "go deeper / go over the plan / go for a walk".
 */
export function isSessionLeaveWithOptionalReconnect(rawText) {
  const t = norm(rawText);
  if (!t) return false;
  if (!isGoPhraseSessionFarewell(t) && !matchesAny(t, CLOSING_PATTERNS)) return false;
  // Pure leave-taking, or leave-taking + reconnect/timing ask.
  if (LEAVE_TAKING_CONTINUATION.test(t)) return true;
  if (isGoPhraseSessionFarewell(t) && wordCount(t) <= 16) return true;
  return false;
}

/**
 * Leave-taking "go / heading out" cues that end the conversation — not travel plans.
 * "I'm going to go for a hike" is activity purpose; "I'm going to go now" is farewell.
 */
export function isGoPhraseSessionFarewell(rawText) {
  const t = norm(rawText);
  if (!t) return false;
  // Exercise plans are not leave-taking ("I'm going for a run later").
  if (/\bgoing for a (run|jog|walk|hike)\b/i.test(t) && !/\b(got to|have to|need to|gotta) (go|run)\b/i.test(t)) {
    return false;
  }

  const goPatterns = [
    /\bi(?:'| a)?m (?:gonna|going to) (?:go|head out|sign off|leave)\b/gi,
    /\bi(?:'| a)?m heading out\b/gi,
    /\bi (?:have to|need to|gotta|got to) go\b/gi,
    /\bi(?:'| a)?ve (?:got to|gotta) go\b/gi,
    /\bgotta go\b/gi,
    /\bgot to go\b/gi,
    /\bi should get going\b/gi,
    /\bi need to go for now\b/gi,
  ];
  const runPatterns = [
    /\bi (?:have to|need to|gotta|got to) run\b/gi,
    /\bi(?:'| a)?ve (?:got to|gotta) run\b/gi,
    /\bgotta run\b/gi,
    /\bgot to run\b/gi,
  ];

  let sawLeaveTaking = false;
  for (const re of goPatterns) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(t)) !== null) {
      const after = t.slice(m.index + m[0].length);
      if (goRemainderIsActivityPurpose(after)) continue;
      sawLeaveTaking = true;
      break;
    }
    if (sawLeaveTaking) break;
  }
  if (!sawLeaveTaking) {
    for (const re of runPatterns) {
      re.lastIndex = 0;
      let m;
      while ((m = re.exec(t)) !== null) {
        const after = t.slice(m.index + m[0].length);
        if (runRemainderIsActivityPurpose(after)) continue;
        sawLeaveTaking = true;
        break;
      }
      if (sawLeaveTaking) break;
    }
  }
  return sawLeaveTaking;
}

/** Closing pattern match plus semantic go-phrase leave-taking. */
function matchesClosingEvidence(text) {
  const t = norm(text);
  if (isTopicalTalkLaterNotSessionClose(t)) return false;
  if (isGoPhraseSessionFarewell(t)) return true;
  return matchesAny(t, CLOSING_PATTERNS);
}

/**
 * "I'm done with breakfast/scripture/work" = activity completion, not session end.
 * Session-ending forms ("I'm done.", "I'm done for now") stay closing.
 */
export function isActivityCompletionNotSessionEnd(rawText) {
  const t = norm(rawText);
  if (!t) return false;
  // Bare session-ending "I'm done" / "I'm done for now" are NOT activity completion.
  if (/^\s*i(?:'| a)?m done[.!]?\s*$/.test(t)) return false;
  if (/\bi(?:'| a)?m done (for now|talking(?: for today)?|for today|here)(?:\s|$|[.!,])/.test(t)) {
    return false;
  }
  if (/\bi think i(?:'| a)?m done(?: for now)?(?:\s|$|[.!,])/.test(t)) return false;
  // Task / routine completion.
  if (/\bi(?:'| a)?m done (with|watching|reading|eating|praying|working|after)\b/.test(t)) return true;
  if (/\bi just got done\b/.test(t)) return true;
  if (/\bi (?:just )?finished (my|the|a|with)\b/.test(t)) return true;
  if (/\bi finished (breakfast|lunch|dinner|work|practice|reading|scripture)\b/.test(t)) return true;
  if (/\bi(?:'| a)?m finished (with|watching|reading)\b/.test(t)) return true;
  return false;
}

/** True session-closing cues independent of activity-completion language. */
function hasSessionEndingFarewellCue(text) {
  const t = norm(text);
  if (isTopicalTalkLaterNotSessionClose(t)) return false;
  if (
    /\b(good ?bye|goodbye|bye( now)?|good ?night|take care|talk (to you )?(later|soon|again)|talk(?:\s+\w+){0,4}\s+later|speak(?:\s+\w+){0,4}\s+later|look forward to (speaking|talking)|have a (good|great|wonderful|nice) (day|night|one))\b/.test(
      t,
    )
  ) {
    return true;
  }
  if (/^\s*i(?:'| a)?m done[.!]?\s*$/.test(t)) return true;
  if (/\bi(?:'| a)?m done (for now|talking(?: for today)?|for today|here)(?:\s|$|[.!,])/.test(t)) {
    return true;
  }
  if (/\bi think i(?:'| a)?m done(?: for now)?(?:\s|$|[.!,])/.test(t)) return true;
  if (/\bthat'?s all( for now| i wanted to say)?\b/.test(t)) return true;
  if (/\bi(?:'| a)?m going to leave it there\b/.test(t)) return true;
  if (isGoPhraseSessionFarewell(t)) return true;
  return false;
}

