/**
 * True when an opening greets + (optionally) shares status + asks how Philip is.
 * Must not be treated as a bare greeting that re-asks "How are you?"
 */
export function isHybridGreetingReciprocal(rawText) {
  const text = norm(rawText);
  if (!text) return false;
  if (isClosingTurn(text)) return false;
  if (matchesAny(text, CRISIS_PATTERNS) || matchesAny(text, PRACTICAL_PATTERNS)) return false;
  if (wordCount(text) > 28) return false;
  const hasOpener =
    /^\s*(hi|hey|hello|yo|hiya|howdy)\b/.test(text) ||
    /^\s*good (morning|afternoon|evening)\b/.test(text);
  if (!hasOpener) return false;
  if (!matchesAny(text, RECIPROCAL_SMALLTALK_PATTERNS)) return false;
  return true;
}

export function extractOpeningStatusBrief(rawText) {
  const original = String(rawText || "").trim();
  if (!original) return "";
  const t = norm(original);
  if (/\brough (morning|day|night)\b/.test(t)) return "it's been a rough stretch";
  if (/\bi(?:'| a)?m (a little |kind of |kinda )?tired\b/.test(t)) return "you're a little tired";
  if (/\bi(?:'| a)?m (doing )?(pretty |really )?(well|good|fine|great)\b/.test(t) || /\bpretty good\b/.test(t)) {
    return "you're doing pretty well";
  }
  if (/\bnot (too )?bad\b/.test(t) || /\bi(?:'| a)?m (ok|okay|alright|all right)\b/.test(t)) {
    return "you're holding up alright";
  }
  if (matchesAny(t, STATUS_ALREADY_PATTERNS)) return "you've shared how things are";
  return "";
}

/**
 * True when the turn is clearly ending the session (farewell or gratitude+farewell).
 * Bare thanks alone is NOT closing.
 * Order-aware: farewell followed by later substance is NOT a closing turn.
 */
export function isClosingTurn(rawText, state = null) {
  const original = String(rawText || "").trim();
  if (!original) return false;
  if (isTopicalTalkLaterNotSessionClose(original)) return false;
  const multi = analyzeMultiActTurn(original, state);
  if (multi.closingFollowedBySubstance) return false;
  if (multi.socialFarewellReciprocal) return true;
  if (multi.bareGratitude) return false;
  if (multi.substanceFollowedByClosing) {
    // "I'm done with Scripture…" mis-tagged as closing must not end the session.
    if (
      isActivityCompletionNotSessionEnd(multi.closingText || "") &&
      !hasSessionEndingFarewellCue(multi.closingText || "")
    ) {
      return false;
    }
    return true;
  }

  // Activity completion without farewell cues is never a close.
  if (isActivityCompletionNotSessionEnd(original) && !hasSessionEndingFarewellCue(original)) {
    return false;
  }

  const text = norm(original);
  if (matchesAny(text, CRISIS_PATTERNS)) return false;
  if (matchesAny(text, PRAYER_REQUEST_PATTERNS)) return false;

  const hasClosing = matchesClosingEvidence(text);
  const leaveWithReconnect = isSessionLeaveWithOptionalReconnect(original);
  if (!hasClosing && !leaveWithReconnect) {
    // Emotional / practical disclosures without farewell evidence are not closings.
    if (matchesAny(text, EMOTIONAL_PATTERNS) && wordCount(text) >= 14) return false;
    if (matchesAny(text, PRACTICAL_PATTERNS)) return false;
    return false;
  }

  // Leave-taking wins over "I feel like I need to go…" emotional false routes,
  // including soft reconnect questions ("can we reconnect later?").
  if (leaveWithReconnect && wordCount(text) <= 55) return true;

  // Farewell can be longer when it's clearly a wrap-up ("look forward to talking again…").
  if (wordCount(text) <= 8) return true;
  if (wordCount(text) <= 36 && !/[?]/.test(text)) return true;
  // Grateful + farewell with a short question about tomorrow timing still closes.
  if (
    wordCount(text) <= 40 &&
    matchesAny(text, GRATITUDE_PATTERNS) &&
    /\b(tomorrow|later|soon|again|good day|take care|bye)\b/.test(text)
  ) {
    return true;
  }
  // Practical ask alone without leave-taking evidence should not close.
  if (matchesAny(text, PRACTICAL_PATTERNS) && !leaveWithReconnect && !isGoPhraseSessionFarewell(text)) {
    return false;
  }
  return false;
}


/**
 * Leading content before a trailing reciprocal check-in.
 * Empty when the turn is reciprocal-only or has only a brief status preface.
 */
export function extractTextBeforeTrailingReciprocal(rawText) {
  const original = String(rawText || "").trim();
  if (!original) return "";
  const stripped = original
    .replace(
      /[.!?]?\s*(?:(?:and|so|but)\s+)?(?:how (?:about|are) (?:you|yourself)(?: doing| today)?|how you(?:'| a)?re (?:doing|feeling|holding up)|what about you|and (?:you|yourself))\s*\??\s*$/i,
      "",
    )
    .trim();
  if (!stripped || stripped === original) return "";
  return stripped;
}

export function isReciprocalSmallTalk(rawText) {
  const text = norm(rawText);
  if (!text) return false;
  if (isClosingTurn(text)) return false;
  if (matchesAny(text, PRACTICAL_PATTERNS) && !matchesAny(text, RECIPROCAL_SMALLTALK_PATTERNS)) {
    return false;
  }
  // Hybrid openings are reciprocal even with a greeting opener.
  if (isHybridGreetingReciprocal(text)) return true;
  // Short reciprocal check-ins, optionally after a brief status ("I'm pretty good. How about yourself?")
  if (!matchesAny(text, RECIPROCAL_SMALLTALK_PATTERNS)) return false;

  // Multi-topic: real substance then reciprocal must not collapse to pure small-talk
  // (contribution should answer both). Brief status prefaces stay reciprocal.
  const before = extractTextBeforeTrailingReciprocal(rawText);
  if (before) {
    const b = norm(before);
    const briefStatus = matchesAny(b, STATUS_ALREADY_PATTERNS) && wordCount(b) <= 10;
    if (!briefStatus && wordCount(b) >= 6) return false;
  }

  if (wordCount(text) <= 14) return true;
  // Longer only if the reciprocal ask is the main move and there's no heavy ask.
  if (wordCount(text) <= 20 && !matchesAny(text, EMOTIONAL_PATTERNS)) return true;
  return false;
}

